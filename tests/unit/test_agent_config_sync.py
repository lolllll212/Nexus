"""Guard against MCP registration drift across the three agent config files.

opencode.json is canonical; .vscode/mcp.json and .agent/mcp_config.json are
generated by scripts/sync_agent_config.py. If these tests fail, run:

    python scripts/sync_agent_config.py
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "scripts"))

import sync_agent_config as sync  # noqa: E402


def _spec():
    spec = importlib.util.spec_from_file_location(
        "sync_agent_config", REPO_ROOT / "scripts" / "sync_agent_config.py"
    )
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_canonical_has_nexus_and_rea():
    canonical = sync.load_canonical()
    assert {"nexus", "rea"} <= set(canonical)


def test_vscode_and_agent_match_canonical():
    canonical = sync.load_canonical()
    vscode = (REPO_ROOT / ".vscode" / "mcp.json").read_text(encoding="utf-8")
    agent = (REPO_ROOT / ".agent" / "mcp_config.json").read_text(encoding="utf-8")
    import json

    assert json.loads(vscode) == sync.build_vscode(canonical)
    assert json.loads(agent) == sync.build_agent(canonical)


def test_check_mode_detects_drift(tmp_path):
    mod = _spec()
    canonical = {"demo": {"type": "local", "command": ["python", "x.py"], "enabled": True}}
    generated = mod.build_vscode(canonical)
    generated["servers"]["demo"]["command"] = "stale-python"
    assert generated != mod.build_vscode(canonical)


def test_new_server_propagates():
    canonical = dict(sync.load_canonical())
    canonical["future-server"] = {
        "type": "local",
        "command": ["python", "scripts/future.py"],
        "enabled": True,
        "environment": {},
    }
    vscode = sync.build_vscode(canonical)
    agent = sync.build_agent(canonical)
    assert vscode["servers"]["future-server"]["args"] == ["scripts/future.py"]
    assert agent["mcpServers"]["future-server"]["args"] == ["scripts/future.py"]
